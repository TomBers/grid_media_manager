defmodule GridMediaManager.RationalGrid.Explorations do
  @moduledoc "Durable exploration proposals, generation jobs and campaign provenance."
  import Ecto.Query
  alias GridMediaManager.{Repo, Campaigns}
  alias GridMediaManager.RationalGrid.{Accounts, Exploration, ImportAdapter, MCP}

  def list, do: Repo.all(from e in Exploration, order_by: [desc: e.id], limit: 50)
  def get!(id), do: Repo.get!(Exploration, id)

  def propose(attrs, evidence, target \\ nil) do
    case Accounts.connection() do
      %{id: connection_id, status: "connected"} ->
        args = if target, do: target, else: %{}
        tool = if target, do: "add_grid_idea", else: "explore_question"

        %Exploration{
          request_id: Ecto.UUID.generate(),
          connection_id: connection_id,
          evidence: Jason.decode!(Jason.encode!(evidence)),
          tool: tool,
          arguments: args
        }
        |> Exploration.proposal_changeset(attrs)
        |> Repo.insert()

      _ ->
        {:error, :reauthorization_required}
    end
  end

  def recommend(theme) do
    feedback = GridMediaManager.Social.Performance.editorial_feedback()

    sources =
      for c <- Campaigns.list_campaigns() |> Enum.take(30) do
        %{
          grid_id: c.raw_payload["metadata"]["id"] || c.slug,
          title: c.title,
          visibility: c.raw_payload["metadata"]["visibility"] || "public",
          nodes:
            GridMediaManager.RationalGrid.MediaPayload.key_nodes(c.raw_payload)
            |> Enum.take(12)
            |> Enum.map(&Map.take(&1, ["id", "title", "excerpt"]))
        }
      end

    selector =
      Application.get_env(
        :grid_media_manager,
        :exploration_selector,
        GridMediaManager.Automation.LLMSelector
      )

    with {:ok, proposal} <- selector.propose_exploration(theme, feedback, sources),
         {:ok, target} <- validate_target(proposal, sources) do
      propose(proposal, %{feedback: feedback, source_records: sources, theme: theme}, target)
    end
  end

  defp validate_target(%{"kind" => "new_question"}, _), do: {:ok, nil}

  defp validate_target(
         %{"kind" => "improve_grid", "grid_id" => id, "parent_node_id" => node},
         sources
       ) do
    if Enum.any?(sources, fn s ->
         s.grid_id == id and s.visibility == "private" and Enum.any?(s.nodes, &(&1["id"] == node))
       end),
       do: {:ok, %{"grid_id" => id, "parent_node_id" => node, "kind" => "question"}},
       else: {:error, :invalid_target}
  end

  defp validate_target(_, _), do: {:error, :invalid_proposal}

  def start(id) do
    Repo.transaction(fn ->
      e = Repo.one!(from e in Exploration, where: e.id == ^id, lock: "FOR UPDATE")

      if e.status == "proposed" do
        args =
          if e.tool == "explore_question",
            do: %{"question" => e.question},
            else: Map.put(e.arguments, "content", e.question)

        save(e, %{
          status: "queued",
          arguments: Map.put(args, "request_id", e.request_id),
          next_run_at: now()
        })
      else
        e
      end
    end)
  end

  # Resumes the identical request after reauthorization or an uncertain transport error.
  # A failed generation is terminal; it is never regenerated by this function.
  def retry(id) do
    Repo.transaction(fn ->
      e = Repo.one!(from e in Exploration, where: e.id == ^id, lock: "FOR UPDATE")

      if e.status in ["retry", "needs_access"] do
        save(e, %{status: "queued", attempts: 0, next_run_at: now(), error: nil})
      else
        e
      end
    end)
  end

  def process_next do
    # Claim briefly, then commit before HTTP. In particular, rotating OAuth credentials
    # must survive a later import or worker failure. A crashed claim becomes due again.
    claim =
      Repo.transaction(fn ->
        e =
          Repo.one(
            from e in Exploration,
              where: e.status in ["queued", "generating"] and e.next_run_at <= ^now(),
              order_by: e.next_run_at,
              limit: 1,
              lock: "FOR UPDATE SKIP LOCKED"
          )

        if e, do: save(e, %{next_run_at: DateTime.add(now(), 300)}), else: nil
      end)

    case claim do
      {:ok, nil} -> {:ok, :idle}
      {:ok, e} -> {:ok, process(e)}
      error -> error
    end
  end

  defp process(e) do
    result =
      if map_size(e.result) == 0 do
        with :ok <- verify_edit_target(e), do: MCP.call(e.tool, e.arguments)
      else
        MCP.call("get_operation", %{"request_id" => e.request_id})
      end

    case result do
      {:ok, %{"request_id" => id, "status" => status} = result} when id == e.request_id ->
        e = save(e, %{result: result, error: nil})

        case status do
          "completed" ->
            finish(e)

          "failed" ->
            save(e, %{
              status: "failed",
              error: "Generation failed. The partial grid is preserved."
            })

          s when s in ["queued", "generating"] ->
            save(e, %{status: "generating", next_run_at: DateTime.add(now(), 5)})

          _ ->
            save(e, %{
              status: "retry",
              error: "Operation status is unknown; inspect the source before resuming."
            })
        end

      {:error, reason} ->
        fail_or_retry(e, reason)

      _ ->
        fail_or_retry(e, :invalid_tool_response)
    end
  end

  defp verify_edit_target(%{tool: "explore_question"}), do: :ok

  defp verify_edit_target(e) do
    with {:ok, grid} <- MCP.read_all(e.arguments["grid_id"]),
         true <- grid["grid"]["visibility"] == "private",
         true <- Enum.any?(grid["nodes"], &(&1["id"] == e.arguments["parent_node_id"])) do
      :ok
    else
      {:error, _} = error -> error
      _ -> {:error, :private_target_required}
    end
  end

  defp finish(e) do
    with id when is_binary(id) <- get_in(e.result, ["grid", "id"]),
         {:ok, grid} <- MCP.read_all(id) do
      save(e, %{status: "review", payload: ImportAdapter.payload(grid, e.result), attempts: 0})
    else
      {:error, reason} -> fail_or_retry(e, reason)
      _ -> fail_or_retry(e, :invalid_grid_response)
    end
  end

  defp fail_or_retry(e, reason) do
    status =
      cond do
        reason in [:reauthorization_required, :unauthorized, :access_denied] -> "needs_access"
        reason == :private_target_required -> "failed"
        reason in [:tool_failed, :rpc_error] -> "retry"
        e.attempts >= 4 -> "retry"
        true -> e.status
      end

    save(e, %{
      status: status,
      attempts: e.attempts + 1,
      next_run_at: DateTime.add(now(), min(300, 5 * Integer.pow(2, min(e.attempts, 6)))),
      error: error_message(reason)
    })
  end

  def create_campaign(id) do
    Repo.transaction(fn ->
      e = Repo.one!(from e in Exploration, where: e.id == ^id, lock: "FOR UPDATE")

      cond do
        e.campaign_id ->
          Campaigns.get_campaign!(e.campaign_id)

        e.status == "review" ->
          case Campaigns.import_payload(e.payload, e.payload["metadata"]["id"]) do
            {:ok, campaign} ->
              save(e, %{campaign_id: campaign.id, status: "imported"})
              campaign

            {:error, reason} ->
              Repo.rollback(reason)
          end

        true ->
          Repo.rollback(:not_ready)
      end
    end)
  end

  def outcomes(e) do
    if e.campaign_id do
      GridMediaManager.Social.Platforms.ids()
      |> Enum.flat_map(&GridMediaManager.Social.Performance.results/1)
      |> Enum.filter(&(&1.campaign_id == e.campaign_id))
    else
      []
    end
  end

  def error_message(:reauthorization_required),
    do: "Connect or reauthorize RationalGrid to continue."

  def error_message(:access_denied),
    do: "The linked account cannot access this grid. Reauthorize or check access."

  def error_message(:private_target_required),
    do: "Choose an accessible private grid and an existing node."

  def error_message(_),
    do: "RationalGrid could not complete this request. Resume uses the same request UUID."

  defp save(e, attrs), do: e |> Ecto.Changeset.change(attrs) |> Repo.update!()
  defp now, do: DateTime.utc_now() |> DateTime.truncate(:second)
end
